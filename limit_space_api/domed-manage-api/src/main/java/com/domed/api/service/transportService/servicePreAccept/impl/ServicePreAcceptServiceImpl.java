    private void validatePagination(String currentPage, String numberPage) {
        try {
            int page = Integer.parseInt(currentPage);
            int size = Integer.parseInt(numberPage);
            if (page < 1 || size < 1 || size > 1000) {
                throw new ApplicationException("Invalid pagination parameters");
            }
        } catch (NumberFormatException e) {
            throw new ApplicationException("Invalid pagination parameters");
        }
    }

    private int parseEfficiency(String value) {
        if (!"0".equals(value.trim()) && !"1".equals(value.trim())) {
            throw new ApplicationException("Invalid efficiency filter");
        }
        return Integer.parseInt(value.trim());
    }
